class Graph:
    def __init__(self, design: Path):
        self.design = design
        self.data = load_json(design / GRAPH_REL)
        self.tasks = {t['id']: t for t in self.data['tasks']}
        self.lanes = {l['id']: l for l in self.data['lanes']}
        self.repos = {r['id']: r for r in self.data['repositories']}
        self.subs = {s['id']: s for s in self.data.get('substitutes', [])}
        self.res = {r['id']: r for r in self.data.get('sharedResources', [])}
        self.pobs = {p['id']: p for p in self.data.get('packageObligations', [])}
        self.gates = {g['gate']: g for g in self.data.get('gates', [])}
        self.catalogue = substeps(design)

    def start_edges(self, t):
        return [e for e in t.get('start', [])]

    def complete_edges(self, t):
        return [e for e in t.get('complete', [])]

    def entry(self, tid):
        """Adoption entry task of the owning repository (DLV-22), if any."""
        t = self.tasks[tid]
        a = self.repos.get(t['repo'], {}).get('adoptionTask')
        if not a or a == tid or t.get('kind') == 'adoption' or t['baseline']['state'] == 'accepted':
            return None
        return a

    def starts(self, tid):
        t = self.tasks[tid]
        s = [e['task'] for e in t.get('start', [])]
        a = self.entry(tid)
        return s + ([a] if a and a not in s else [])

    def preds(self, tid):
        t = self.tasks[tid]
        return self.starts(tid) + [e['task'] for e in t.get('complete', [])]

    def succ_map(self):
        succ = defaultdict(set)
        for tid, t in self.tasks.items():
            for e in t.get('start', []) + t.get('complete', []):
                succ[e['task']].add(tid)
        return succ

    def events(self):
        """Event graph (DLV-21): D(t)=delivered, C(t)=complete.

        D(t) needs D(s) for each contract/artifact/design start prerequisite s (and the adoption entry),
        C(s) for each release prerequisite; C(t) needs D(t) and C(s) for each completion prerequisite s.
        """
        adj = defaultdict(set)
        for tid, t in self.tasks.items():
            for e in t.get('start', []):
                adj[('D', tid)].add(('C' if e['type'] == 'release' else 'D', e['task']))
            ent = self.entry(tid)
            if ent:
                adj[('D', tid)].add(('C', ent))
            adj[('C', tid)].add(('D', tid))
            for e in t.get('complete', []):
                adj[('C', tid)].add(('C', e['task']))
        return adj

    def event_order(self):
        adj = self.events()
        nodes = {(k, t) for t in self.tasks for k in ('D', 'C')}
        indeg = {n: 0 for n in nodes}
        rev = defaultdict(set)
        for n, ps in adj.items():
            for p in ps:
                if p in nodes:
                    indeg[n] += 1
                    rev[p].add(n)
        q = deque(sorted(n for n, d in indeg.items() if d == 0))
        order = []
        while q:
            n = q.popleft()
            order.append(n)
            for m in sorted(rev.get(n, ())):
                indeg[m] -= 1
                if indeg[m] == 0:
                    q.append(m)
        stuck = sorted({t for (k, t), d in indeg.items() if d > 0})
        return order, stuck

    def topo(self):
        indeg = {t: 0 for t in self.tasks}
        succ = self.succ_map()
        for tid in self.tasks:
            for p in set(self.preds(tid)):
                if p in self.tasks:
                    indeg[tid] += 1
        q = deque(sorted(t for t, d in indeg.items() if d == 0))
        order = []
        while q:
            n = q.popleft()
            order.append(n)
            for s in sorted(succ.get(n, ())):
                indeg[s] -= 1
                if indeg[s] == 0:
                    q.append(s)
        return order, [t for t, d in indeg.items() if d > 0]

    def ancestors(self, tid, cache={}):
        key = (id(self), tid)
        if key in cache:
            return cache[key]
        seen, stack = set(), list(self.preds(tid))
        while stack:
            p = stack.pop()
            if p in seen or p not in self.tasks:
                continue
            seen.add(p)
            stack.extend(self.preds(p))
        cache[key] = seen
        return seen

    def obligation_map(self):
        m = defaultdict(list)
        for t in self.data['tasks']:
            for o in t.get('obligations', []):
                m[o['ref']].append((t['id'], o.get('part', '')))
        return m


def validate(g: Graph) -> tuple[list[str], list[str]]:
    errors, warnings = [], []
    ids = [t['id'] for t in g.data['tasks']]
    for tid, n in Counter(ids).items():
        if n > 1:
            errors.append(f'duplicate task id {tid}')
    required = ['id', 'title', 'lane', 'repo', 'kind', 'size', 'obligations', 'outcome', 'start',
                'complete', 'writes', 'validation', 'evidence', 'baseline']
    for t in g.data['tasks']:
        tid = t.get('id', '?')
        for f in required:
            if f not in t:
                errors.append(f'{tid}: missing field {f}')
        if not TASK_ID.match(tid):
            errors.append(f'{tid}: invalid task id format')
        if CORPUS_ID.search(t.get('title', '')):
            errors.append(f'{tid}: title contains a corpus identifier; keep identifiers in obligations')
        if t.get('lane') not in g.lanes:
            errors.append(f'{tid}: unknown lane {t.get("lane")}')
        elif not tid.startswith(g.lanes[t['lane']]['prefix'] + '.'):
            errors.append(f'{tid}: prefix does not match lane {t["lane"]}')
        if t.get('repo') not in g.repos:
            errors.append(f'{tid}: unknown repository {t.get("repo")}')
        for r in t.get('alsoTouches', []):
            if r not in g.repos:
                errors.append(f'{tid}: unknown touched repository {r}')
        if t.get('kind') not in KINDS:
            errors.append(f'{tid}: unknown kind {t.get("kind")}')
        if t.get('size') not in SIZES:
            errors.append(f'{tid}: unknown size {t.get("size")}')
        if not t.get('obligations'):
            errors.append(f'{tid}: no obligations')
        for o in t.get('obligations', []):
            ref = o.get('ref', '')
            if SUBSTEP.match(ref):
                if ref not in g.catalogue:
                    errors.append(f'{tid}: obligation {ref} is not an active substep')
            elif POB_ID.match(ref):
                if ref not in g.pobs:
                    errors.append(f'{tid}: unknown package obligation {ref}')
            elif DECISION.match(ref):
                if t.get('kind') not in {'adoption', 'governance'}:
                    errors.append(f'{tid}: decision obligation {ref} is reserved for adoption/governance tasks')
            else:
                errors.append(f'{tid}: invalid obligation reference {ref}')
            if not o.get('part'):
                errors.append(f'{tid}: obligation {ref} lacks part text')
        for kind, allowed in (('start', START_TYPES), ('complete', COMPLETE_TYPES)):
            seen = set()
            for e in t.get(kind, []):
                tgt = e.get('task')
                if e.get('type') not in allowed:
                    errors.append(f'{tid}: {kind} edge to {tgt} has invalid type {e.get("type")}')
                if tgt not in g.tasks:
                    errors.append(f'{tid}: {kind} edge to unknown task {tgt}')
                if tgt == tid:
                    errors.append(f'{tid}: self edge')
                if tgt in seen:
                    errors.append(f'{tid}: duplicate {kind} edge to {tgt}')
                seen.add(tgt)
                if not (e.get('why') or '').strip() or not (e.get('need') or '').strip():
                    errors.append(f'{tid}: {kind} edge to {tgt} lacks need/why')
                if e.get('type') == 'release' and t.get('kind') not in {'release', 'acceptance'}:
                    errors.append(f'{tid}: release edge on a non-release task')
        for s in t.get('substitutes', []):
            if s not in g.subs:
                errors.append(f'{tid}: unknown substitute {s}')
        for sh in t.get('shared', []):
            if sh.get('resource') not in g.res:
                errors.append(f'{tid}: unknown shared resource {sh.get("resource")}')
            if sh.get('mode') not in MODES:
                errors.append(f'{tid}: invalid shared mode {sh.get("mode")}')
        for w in t.get('writes', []):
            repo = w.split(':', 1)[0]
            if ':' not in w or (repo not in g.repos and repo != '*'):
                errors.append(f'{tid}: invalid write scope {w}')
        b = t.get('baseline', {})
        if b.get('state') not in BASELINE:
            errors.append(f'{tid}: invalid baseline state {b.get("state")}')
        if b.get('state') == 'accepted' and not b.get('evidence'):
            errors.append(f'{tid}: accepted baseline without evidence')
    for l in g.lanes.values():
        if l['repo'] not in g.repos and l['repo'] != 'multiple':
            errors.append(f'lane {l["id"]}: unknown repository {l["repo"]}')
    _, stuck = g.event_order()
    if stuck:
        errors.append(f'unsatisfiable prerequisites (deadlock) among {len(stuck)} tasks: {stuck[:12]}')
    # Obligation coverage.
    om = g.obligation_map()
    for sid in g.catalogue:
        if sid not in om:
            errors.append(f'substep {sid} is not mapped to any task')
        elif len(om[sid]) > 1 and any(p.strip().lower() == 'full' for _, p in om[sid]):
            warnings.append(f'substep {sid} mapped by {len(om[sid])} tasks but one claims "full"')
    for pid in g.pobs:
        if pid not in om:
            errors.append(f'package obligation {pid} is not mapped to any task')
    for s in g.pobs.values():
        if not POB_ID.match(s['id']):
            errors.append(f'invalid package obligation id {s["id"]}')
    # Substitutes.
    users = defaultdict(list)
    for t in g.data['tasks']:
        for s in t.get('substitutes', []):
            users[s].append(t['id'])
    for sid, s in g.subs.items():
        if not SUB_ID.match(sid):
            errors.append(f'invalid substitute id {sid}')
        for f in ('standsInFor', 'contract', 'proves', 'realProducer', 'replacedBy', 'realEvidence'):
            if not s.get(f):
                errors.append(f'{sid}: missing {f}')
        rp = s.get('realProducer', [])
        rp = rp if isinstance(rp, list) else [rp]
        rb = s.get('replacedBy')
        for p in rp:
            if p not in g.tasks:
                errors.append(f'{sid}: unknown real producer {p}')
        if rb not in g.tasks:
            errors.append(f'{sid}: unknown replacing task {rb}')
            continue
        anc = g.ancestors(rb)
        for p in rp:
            if p in g.tasks and p != rb and p not in anc:
                errors.append(f'{sid}: replacing task {rb} does not depend on real producer {p}')
        for u in users.get(sid, []):
            if u != rb and u not in anc:
                errors.append(f'{sid}: replacing task {rb} does not depend on consumer {u}')
        if not users.get(sid):
            warnings.append(f'{sid}: substitute not used by any task')
        if g.tasks[rb].get('kind') not in {'integration', 'acceptance', 'release', 'service', 'producer', 'feature'}:
            warnings.append(f'{sid}: replacing task {rb} has kind {g.tasks[rb].get("kind")}')
    # Shared resources.
    for rid, r in g.res.items():
        if not RES_ID.match(rid):
            errors.append(f'invalid shared resource id {rid}')
        if r.get('ownerRepo') not in g.repos and r.get('ownerRepo') not in {'multiple', 'workstation'}:
            errors.append(f'{rid}: unknown owner repository {r.get("ownerRepo")}')
        for f in ('kind', 'owner', 'protocol', 'title'):
            if not r.get(f):
                errors.append(f'{rid}: missing {f}')
    # The same exact file written by two unordered tasks must be a declared shared resource.
    # Different files inside one module directory are ordinary parallel work resolved by Git.
    by_repo = defaultdict(list)
    for t in g.data['tasks']:
        for w in t.get('writes', []):
            repo, path = w.split(':', 1)
            path = path.split(' (', 1)[0].strip()
            if '*' in path or path.endswith('/') or not path:
                continue
            by_repo[repo].append((t['id'], path))
    shared_of = {t['id']: {s['resource'] for s in t.get('shared', [])} for t in g.data['tasks']}
    for repo, items in by_repo.items():
        for i in range(len(items)):
            a, pa = items[i]
            for j in range(i + 1, len(items)):
                b, pb = items[j]
                if a == b:
                    continue
                if pa != pb:
                    continue
                if a in g.ancestors(b) or b in g.ancestors(a):
                    continue
                if shared_of[a] & shared_of[b]:
                    continue
                warnings.append(f'unordered write overlap {a} ~ {b} in {repo}: {pa} / {pb}')
    # Gates.
    for gate, rec in g.gates.items():
        for tid in rec.get('tasks', []):
            if tid not in g.tasks:
                errors.append(f'gate {gate}: unknown task {tid}')
    return errors, warnings


