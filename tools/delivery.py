def render_wp_block(g: Graph, wp: str, rel: str) -> str:
    L = Linker(g.design, rel)
    mapped = defaultdict(list)
    for t in g.data['tasks']:
        for o in t['obligations']:
            m = SUBSTEP.match(o['ref']) or POB_ID.match(o['ref'])
            if m and m[1] == wp:
                mapped[t['id']].append(o)
    own = sorted(mapped, key=lambda x: (g.tasks[x]['lane'], x))
    lines = [BEGIN, '',
             'Scheduling is task-level under [P2-018](../../decisions/phase-2-specification-decisions.md#rule-p2-018). '
             'This package is an obligation set; it is satisfied when every task below is complete with its evidence. '
             'Prerequisites are typed task edges, never "all upstream packages complete".', '',
             '| Delivery task | Satisfies | Start prerequisites outside this package |', '|---|---|---|']
    own_set = set(own)
    for tid in own:
        t = g.tasks[tid]
        sat = '<br>'.join(f'{obligation_link(g, L, o["ref"])} ({L.text(o["part"])})' for o in mapped[tid])
        ext = ', '.join(f'{task_link(g, e["task"], rel)} ({e["type"]})' for e in t['start'] if e['task'] not in own_set) or 'none'
        lines.append(f'| {task_link(g, tid, rel)} | {sat} | {ext} |')
    succ = g.succ_map()
    consumers = sorted({s for tid in own for s in succ.get(tid, ()) if s not in own_set})
    lines.append('')
    lines.append('**Consumers outside this package:** ' + (', '.join(task_link(g, c, rel) for c in consumers) or 'none') + '.')
    lines.append('')
    lines.append(END)
    if L.unknown:
        raise Fail(f'{rel}: unresolved identifiers {sorted(L.unknown)}')
    return '\n'.join(lines)


def splice(text: str, block: str) -> str:
    if BEGIN in text:
        pre, rest = text.split(BEGIN, 1)
        _, post = rest.split(END, 1)
        return pre + block + post
    raise Fail('missing generated delivery block markers')


