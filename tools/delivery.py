BEGIN = '<!-- delivery-graph:begin (generated by Plan tools/delivery.py; do not edit) -->'
END = '<!-- delivery-graph:end -->'


class Fail(Exception):
    pass


def slug(task_id: str) -> str:
    return 'task-' + task_id.lower().replace('.', '-')


def load_json(path: Path):
    def hook(pairs):
        out = {}
        for k, v in pairs:
            if k in out:
                raise Fail(f'duplicate JSON key {k} in {path}')
            out[k] = v
        return out
    return json.loads(path.read_text(encoding='utf-8'), object_pairs_hook=hook)


