def weights(g: Graph):
    return {tid: SIZES[t['size']] for tid, t in g.tasks.items()}


def _event_weights(g: Graph, done):
    return {('D', t): (0 if t in done else SIZES[g.tasks[t]['size']]) for t in g.tasks} | {('C', t): 0 for t in g.tasks}


def critical_path(g: Graph, done: set[str] | None = None):
    """Longest weighted chain on the event graph; a task's work sits on its delivery event."""
    done = done or set()
    order, _ = g.event_order()
    adj = g.events()
    w = _event_weights(g, done)
    finish, prev = {}, {}
    for n in order:
        best, arg = 0, None
        for p in sorted(adj.get(n, ())):
            if finish.get(p, 0) > best:
                best, arg = finish[p], p
        finish[n] = best + w[n]
        prev[n] = arg
    end = max(sorted(finish), key=lambda k: finish[k])
    length = finish[end]
    path = []
    while end:
        if end[0] == 'D' and end[1] not in path:
            path.append(end[1])
        end = prev[end]
    return list(reversed(path)), length


def levels(g: Graph, done: set[str] | None = None):
    """Delivery level: longest chain of unfinished prerequisite deliveries before a task can be delivered."""
    done = done or set()
    order, _ = g.event_order()
    adj = g.events()
    lvl = {}
    for n in order:
        ps = [lvl[p] for p in adj.get(n, ()) if p in lvl]
        base = max(ps) if ps else 0
        lvl[n] = base + (1 if n[0] == 'D' and n[1] not in done else 0)
    return {t: lvl[('D', t)] for t in g.tasks}


def simulate(g: Graph, workers: int, done: set[str] | None = None):
    """List scheduling on the event graph. A worker is busy only while a task's own work runs;
    completion prerequisites delay completion, not the worker. Priority: longest remaining path.
    Repository merge, review and CI capacity are not modelled. Returns makespan in size units."""
    done = set(done or set())
    adj = g.events()
    w = {t: SIZES[g.tasks[t]['size']] for t in g.tasks}
    succ = defaultdict(set)
    for n, ps in adj.items():
        for p in ps:
            succ[p].add(n)
    order, _ = g.event_order()
    rem = {}
    for n in reversed(order):
        rem[n] = (w[n[1]] if n[0] == 'D' else 0) + max((rem[s] for s in succ.get(n, ())), default=0)
    reached = set()
    for t in done:
        reached.add(('D', t)); reached.add(('C', t))
    time, running, heap, queued = 0.0, [], [], set()

    def settle():
        changed = True
        while changed:
            changed = False
            for t in g.tasks:
                c = ('C', t)
                if c not in reached and ('D', t) in reached and adj[c] <= reached:
                    reached.add(c); changed = True
            for t in g.tasks:
                d = ('D', t)
                if d in reached or t in queued:
                    continue
                if adj.get(d, set()) <= reached:
                    heapq.heappush(heap, (-rem[d], t)); queued.add(t)

    settle()
    while len(reached) < 2 * len(g.tasks):
        while heap and (workers <= 0 or len(running) < workers):
            _, t = heapq.heappop(heap)
            heapq.heappush(running, (time + w[t], t))
        if not running:
            raise Fail('simulation deadlock (unsatisfiable prerequisites)')
        end, t = heapq.heappop(running)
        time = end
        reached.add(('D', t))
        settle()
    return time


def old_model_metrics(design: Path):
    """Depth of the retired WP-level graph and the retired serial substep count."""
