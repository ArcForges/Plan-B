class Linker:
    def __init__(self, design: Path, from_rel: str):
        self.design = design
        self.from_dir = str(Path(from_rel).parent.as_posix())
        self.homes = anchor_homes(design)
        self.unknown: set[str] = set()

    def rel(self, target_rel: str) -> str:
        import posixpath
        return posixpath.relpath(target_rel, self.from_dir)

    def home(self, ident: str) -> str | None:
        key = ident.lower()
        m = SUBSTEP.match(ident) or re.match(r'^WP-(\d{2})$', ident)
        if m:
            files = wp_files(self.design)
            f = files.get(m[1])
            return f'{WP_REL}/{f.name}' if f else None
        cands = self.homes.get(key, [])
        if not cands:
            return None
        if len(cands) == 1:
            return cands[0]
        for pref in PREFERRED_HOMES:
            if pref in cands:
                return pref
        return cands[0]

    def link(self, ident: str) -> str:
        h = self.home(ident)
        if not h:
            self.unknown.add(ident)
            return ident
        return f'[{ident}]({self.rel(h)}#rule-{ident.lower()})'

    def text(self, s: str) -> str:
        """Link every corpus identifier outside existing links; strip code spans around IDs."""
        if not s:
            return ''
        s = s.replace('\r', ' ').replace('\n', ' ').replace('|', '/')
        s = re.sub(r'`([^`]*)`', lambda m: m[1] if CORPUS_ID.search(m[1]) else m[0], s)
        out, pos = [], 0
        spans = [m.span() for m in LINK.finditer(s)]
        for m in CORPUS_ID.finditer(s):
            if any(a <= m.start() < b for a, b in spans):
                continue
            out.append(s[pos:m.start()])
            out.append(self.link(m[0]))
            pos = m.end()
        out.append(s[pos:])
        return ''.join(out)


