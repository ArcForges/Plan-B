# generated Design view must be a link to its defining anchor.
CORPUS_ID = re.compile(r'(?<![\w-])(?:WP-\d{2}(?:\.\d{2})?|P2-\d{3}|F-[A-Z]{2}-[1-9]\d*|'
                       r'[A-Z][A-Z0-9]{0,5}-(?:[A-Z]\d{1,3}|\d{2,3}[a-z]?))(?![\w-]|\.\d)')
LINK = re.compile(r'\[([^\]\n]+)\]\(([^)\n]+)\)')
