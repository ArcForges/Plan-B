def wp_files(design: Path) -> dict[str, Path]:
    files = {}
    for p in sorted((design / WP_REL).glob('[0-9][0-9]-*.md')):
        files[p.name[:2]] = p
    return files


def substeps(design: Path) -> dict[str, dict]:
    """Every active numbered substep, parsed from the obligation catalogue headings."""
    out = {}
    for wp, p in wp_files(design).items():
        for line in p.read_text(encoding='utf-8').splitlines():
            m = re.match(r'^### WP-(\d{2})\.(\d{2}) — (.+?)\s*$', line)
            if m:
                sid = f'WP-{m[1]}.{m[2]}'
                out[sid] = {'id': sid, 'wp': m[1], 'title': m[3].rstrip('.'), 'file': p.name}
    return out


def anchor_homes(design: Path) -> dict[str, list[str]]:
    """Map rule identifiers to the documents that define `rule-<id>` anchors."""
    homes = defaultdict(list)
    for p in sorted((design / 'docs').rglob('*.md')):
        rel = p.relative_to(design).as_posix()
        if rel.startswith('docs/deprecated-inputs/') and not rel.endswith('README.md'):
            continue
        for a in ANCHOR.findall(p.read_text(encoding='utf-8')):
            if a.startswith('rule-'):
                homes[a[5:]].append(rel)
    return homes


