def md_escape(s: str) -> str:
    return (s or '').replace('|', '/').replace('\n', ' ').strip()


def task_link(g: Graph, tid: str, from_rel: str) -> str:
    import posixpath
    lane = g.tasks[tid]['lane']
    target = f'{DELIVERY_REL}/lanes/{lane}.md'
    rel = posixpath.relpath(target, str(Path(from_rel).parent.as_posix()))
    if target == from_rel:
        rel = ''
    return f'[{tid}]({rel}#{slug(tid)})'


def generated_header(from_rel: str) -> str:
    import posixpath
    graph = posixpath.relpath(GRAPH_REL, str(Path(from_rel).parent.as_posix()))
    model = posixpath.relpath(f'{DELIVERY_REL}/README.md', str(Path(from_rel).parent.as_posix()))
    return (f'> Generated from [the delivery graph]({graph}) by Plan `tools/delivery.py`; do not edit by hand. '
            f'Rules and definitions: [delivery model]({model}).\n')


